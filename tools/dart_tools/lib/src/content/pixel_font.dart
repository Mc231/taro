/// The glyph rows of [char] (upper-cased), or [kUnknownGlyph].
List<String> glyphOf(String char) =>
    kPixelGlyphs[char.toUpperCase()] ?? kUnknownGlyph;

/// The width in font pixels of [text] set on one line.
int textWidth(String text) =>
    text.isEmpty ? 0 : text.length * kGlyphAdvance - 1;
