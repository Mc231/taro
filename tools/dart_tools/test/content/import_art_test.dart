        run: (_, args) {
          seen = args;
          File(args[args.indexOf('-o') + 1]).writeAsBytesSync([7, 7]);
          return ok('');
        },
      );
      expect(encoder.encode(img.Image(width: 2, height: 2), quality: 80), [
        7,
        7,
      ]);
      expect(seen.sublist(0, 3), ['-quiet', '-q', '80']);
    });

    test('encode fails on a non-zero exit', () {
      final encoder = CwebpEncoder(
        run: (_, _) => ProcessResult(0, 1, '', 'bad input\n'),
      );
      expect(
        () => encoder.encode(img.Image(width: 2, height: 2), quality: 80),
        throwsA(predicate((e) => '$e' == 'cwebp exited 1: bad input')),
      );
