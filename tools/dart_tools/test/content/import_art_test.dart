/// Lossless WebP through the `image` package; [hugeAbove] makes every
/// encode above that quality return an over-budget blob.
final class _FakeEncoder implements ArtEncoder {
  _FakeEncoder({this.hugeAbove, this.fail = false});

  final int? hugeAbove;
  final bool fail;
  final List<int> qualities = [];

  @override
  String describe() {
    if (fail) throw const ArtEncoderException('no encoder');
    return 'fake 1.0';
  }

  @override
  Uint8List encode(img.Image image, {required int quality}) {
    qualities.add(quality);
    if (hugeAbove != null && quality > hugeAbove!) {
      return Uint8List(kArtBudgetBytes + 1);
    }
    return img.WebPEncoder().encode(image);
  }
}

final class _ThrowingEncoder extends _FakeEncoder {
  @override
  Uint8List encode(img.Image image, {required int quality}) =>
      throw const ArtEncoderException('cwebp exited 1: boom');
}

const _width = 30; // @3x width used by the fixtures: 30 × 52, @2x 20 × 34.

Uint8List _png(int w, int h) {
  final image = img.Image(width: w, height: h);
  img.fill(image, color: img.ColorRgb8(40, 30, 90));
  img.fillRect(
    image,
    x1: 2,
    y1: 2,
    x2: w ~/ 2,
    y2: h ~/ 2,
    color: img.ColorRgb8(200, 160, 90),
  );
  return img.encodePng(image);
}

/// A complete source folder (78 cards + back) of [w] × [h] PNGs.
Directory _source({int w = _width, int h = 52}) {
  final dir = Directory.systemTemp.createTempSync('taro_art_src_');
  final png = _png(w, h);
  for (final id in kCardIds) {
    File('${dir.path}/$id.png').writeAsBytesSync(png);
  }
  File('${dir.path}/back.png').writeAsBytesSync(png);
  return dir;
}

const _pubspec = '''
flutter:
  assets:
    # Generated by tools/content build.
