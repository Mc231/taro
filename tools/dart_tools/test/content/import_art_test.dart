/// A minimal repository: specs marker, the real tokens, deck.yaml, pubspec.
Directory _repo() {
  final root = Directory.systemTemp.createTempSync('taro_art_repo_');
  Directory('${root.path}/docs/specs').createSync(recursive: true);
  File('${root.path}/$kTokensPath')
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(
      File('${realRepo.path}/$kTokensPath').readAsStringSync(),
    );
  File('${root.path}/$kDeckYamlPath')
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(
      '# deck\nid: rws_original\nversion: 1\n'
      'artSet: placeholder\n',
    );
  File('${root.path}/$kAppPubspecPath')
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(_pubspec);
  return root;
}

RunResult _run(
  Directory root,
  List<String> args, {
  ArtEncoder? encoder,
  Directory? cwd,
}) {
  final out = StringBuffer();
  final err = StringBuffer();
  final code = runImportArt(
    ['--repo-root', root.path, ...args],
    io: ContentIo(out: out, err: err, cwd: cwd, clock: () => fixtureToday),
    encoderFactory: (_) => encoder ?? _FakeEncoder(),
  );
  return (code: code, out: out.toString(), err: err.toString());
}

